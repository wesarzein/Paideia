"""Browser XLSX/API/PostgreSQL journey, restricted to fresh synthetic phase4b3 labs.

Requires private Playwright/Edge and a file generated by institutional_fixture.py.
Only the validated lab's services may be restarted; no cleanup or real data.
"""

import argparse
import json
import re
import subprocess
import traceback
from pathlib import Path

from playwright.sync_api import expect, sync_playwright


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--fixture", type=Path, required=True)
    parser.add_argument("--browser", required=True)
    parser.add_argument(
        "--resume-consultation",
        action="store_true",
        help="Inspect/restart the already populated synthetic lab; never reset it",
    )
    args = parser.parse_args()
    assert args.fixture.name == "phase4b3.synthetic.xlsx"
    config = dict(
        line.split("=", 1)
        for line in args.config.read_text(encoding="utf-8-sig").splitlines()
        if line and not line.startswith("#") and "=" in line
    )
    project = config["COMPOSE_PROJECT_NAME"]
    assert re.fullmatch(r"paideia-dev-phase4b3[a-z0-9-]*", project)
    alias = project.removeprefix("paideia-dev-")
    assert config["POSTGRES_DB"] == f"paideia_dev_{alias.replace('-', '_')}"
    assert config["POSTGRES_USER"] == "paideia_dev"
    assert 14211 <= int(config["FRONTEND_PORT"]) <= 14229
    assert config["PAIDEIA_ENV_FILE"] == f"config/local/{alias}.env"
    compose = [
        "docker",
        "compose",
        "--env-file",
        str(args.config),
        "-f",
        "docker-compose.environment.yml",
    ]
    base = f"http://localhost:{config['FRONTEND_PORT']}"

    def passed(name, **details):
        print(json.dumps({"check": name, "passed": True, **details}), flush=True)

    def docker_python(code):
        return subprocess.check_output(
            ["docker", "exec", project + "-backend-1", "python", "-c", code], text=True
        )

    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(executable_path=args.browser, headless=True)
        context = browser.new_context()
        context.route(
            "**/*",
            lambda route: route.continue_()
            if route.request.url.startswith(base + "/")
            else route.abort(),
        )
        page = context.new_page()
        page.set_default_timeout(15000)
        page.goto(base + "/login")
        page.locator('input[name="email"]').fill(config["INITIAL_ADMIN_EMAIL"])
        page.locator('input[name="password"]').fill(config["INITIAL_ADMIN_PASSWORD"])
        page.get_by_role("button", name="Iniciar sesión").click()
        expect(page).not_to_have_url(base + "/login")
        headers = {
            "Authorization": "Bearer "
            + page.evaluate("localStorage.getItem('paideia_access_token')")
        }

        def api(method, endpoint, payload=None):
            reply = context.request.fetch(
                base + "/api/v1" + endpoint, method=method, headers=headers, data=payload
            )
            assert reply.ok, "Synthetic API request failed"
            return reply.json()

        def verify_saved(catalog, student, course, period, final):
            # Actual consultation screen, then real restart of this lab's own PostgreSQL.
            page.goto(base + "/calificaciones")
            expect(page.get_by_role("heading", name="Calificaciones", exact=True)).to_be_visible()
            grade = next(g for g in catalog["grades"] if g["id"] == student["grade_id"])
            page.get_by_label(re.compile(r"^Nivel")).select_option(grade["level"])
            page.get_by_label(re.compile(r"^Grado")).select_option(student["grade_id"])
            page.get_by_label(re.compile(r"^Sección")).select_option(student["section_id"])
            page.get_by_label(re.compile(r"^Curso")).select_option(course["id"])
            page.get_by_label(re.compile(r"^Periodo")).select_option(period["id"])
            page.get_by_label("Mes de registro", exact=True).fill("2026-04")
            registered = page.locator("section.table-wrap").last.locator("tbody tr")
            expect(registered).to_have_count(10)
            expect(
                registered.filter(has_text="Actitud").first.locator('input[type="number"]')
            ).to_have_value("5")
            passed("consultation_screen_shows_imported_and_corrected_grades")
            before = docker_python(
                "import json; from app.inspect_database import inventory; "
                "print(json.dumps(inventory(),sort_keys=True))"
            )
            subprocess.run(compose + ["restart", "postgres"], check=True, capture_output=True)
            subprocess.run(
                compose + ["up", "-d", "--wait", "--wait-timeout", "60", "postgres"],
                check=True,
                capture_output=True,
            )
            subprocess.run(
                compose + ["restart", "backend", "frontend"], check=True, capture_output=True
            )
            subprocess.run(
                compose + ["up", "-d", "--wait", "--wait-timeout", "60", "backend", "frontend"],
                check=True,
                capture_output=True,
            )
            after = docker_python(
                "import json; from app.inspect_database import inventory; "
                "print(json.dumps(inventory(),sort_keys=True))"
            )
            assert before == after and api("GET", "/grades") == final
            passed("postgres_restart_persists_grades_snapshots_identity_and_inventory")
            browser.close()

        if args.resume_consultation:
            final = api("GET", "/grades")
            assert len(final) == 10
            assert any(g["score"] == 5 for g in final)
            catalog = api("GET", "/academic/catalog")
            student = next(s for s in api("GET", "/students") if s["student_code"] == "1SA001")
            course = next(c for c in catalog["courses"] if c["id"] == final[0]["course_id"])
            period = next(p for p in catalog["periods"] if p["id"] == final[0]["period_id"])
            verify_saved(catalog, student, course, period, final)
            return

        assert api("GET", "/grades") == [], "Fresh lab required; never reset existing data"
        students = api("GET", "/students")
        student = next(s for s in students if s["student_code"] == "1SA001")
        # Two identical synthetic names prove that the UI must not choose by name alone.
        for pupil in students[:2]:
            api(
                "PATCH",
                f"/students/{pupil['id']}",
                {"first_name": "AMBIGUO", "last_name": "SINTETICO"},
            )
        catalog = api("GET", "/academic/catalog")
        course, period = catalog["courses"][0], catalog["periods"][0]
        components = api("GET", f"/courses/{course['id']}/assessment-components")
        component = next((item for item in components if item["name"] == "Cuaderno"), None)
        if component is None:
            component = api(
                "POST",
                f"/courses/{course['id']}/assessment-components",
                {"name": "Cuaderno", "weight": 2},
            )
        assert component["weight"] == 2
        page.goto(base + "/importacion")
        page.get_by_role("button", name="Calificaciones", exact=True).click()
        page.get_by_label(re.compile(r"^Curso")).select_option(course["id"])
        page.get_by_label(re.compile(r"^Periodo")).select_option(period["id"])
        with page.expect_response(lambda r: "/imports/grades/preview" in r.url) as reply:
            page.locator('input[type="file"]').set_input_files(args.fixture)
        assert reply.value.status == 200
        expect(page.get_by_role("heading", name="Vista previa: 10 filas")).to_be_visible()
        preview = reply.value.json()
        assert preview["errors"] and preview["institutional"]["blank_inputs"] == 150
        assert len(preview["institutional"]["derived"]) == 64
        assert all(not row["assessment_date"] for row in preview["rows"])
        confirmation = page.get_by_role("button", name="Confirmar e importar calificaciones")
        review = page.get_by_role("button", name="Revisar registros existentes")
        expect(confirmation).to_be_disabled()
        page.get_by_label("Año académico", exact=True).fill("2026")
        page.get_by_label("Bimestre", exact=True).fill("1")
        page.get_by_label(re.compile(r"^Grado institucional")).select_option(student["grade_id"])
        page.get_by_label(re.compile(r"^Sección institucional")).select_option(
            student["section_id"]
        )
        page.get_by_label("Evaluación 1 MES", exact=True).fill("Bloque abril confirmado")
        page.get_by_label("Fecha 1 MES", exact=True).fill("2026-04-01")
        page.get_by_label("Evaluación 2 MES", exact=True).fill("Bloque mayo confirmado")
        page.get_by_label("Fecha 2 MES", exact=True).fill("2026-04-29")
        page.get_by_label("Confirmo curso, periodo", exact=False).check()
        with page.expect_response(lambda r: "/imports/grades/review" in r.url) as reply:
            review.click()
        assert reply.value.status == 422  # Invalid mark and unresolved external code.
        assert api("GET", "/grades") == []
        passed("xlsx_headers_merges_formulas_and_blocking_errors")
        for index in range(1, 11):
            page.get_by_label(f"Estudiante fila {index}", exact=True).select_option("1SA001")
        page.get_by_label("score fila 1", exact=True).fill("0")
        with page.expect_response(lambda r: "/imports/grades/review" in r.url) as reply:
            review.click()
        assert reply.value.status == 200
        assert reply.value.json()["reference_results"][0]["final"] == 16
        expect(confirmation).to_be_enabled()
        expect(page.get_by_label("score fila 1", exact=True)).to_have_value("0")
        with page.expect_response(lambda r: "/imports/grades/commit" in r.url) as reply:
            confirmation.click()
        assert reply.value.json()["imported"] == 10
        saved = api("GET", "/grades")
        assert len(saved) == 10 and any(g["score"] == 0 for g in saved)
        passed("manual_mapping_correct_zero_revalidate_confirm_and_store", records=10)

        # An identical revalidation skips all ten, including the corrected zero.
        with page.expect_response(lambda r: "/imports/grades/review" in r.url) as reply:
            review.click()
        assert all(r["status"] == "identical" for r in reply.value.json()["rows"])
        with page.expect_response(lambda r: "/imports/grades/commit" in r.url) as reply:
            confirmation.click()
        assert reply.value.json()["skipped"] == 10
        assert api("GET", "/grades") == saved
        passed("identical_reimport_no_duplicates")

        first = next(
            g
            for g in saved
            if g["evaluation_type"].startswith("Actitud") and g["assessment_date"] == "2026-04-01"
        )
        api("PATCH", f"/grades/{first['id']}", {"score": 17})
        with page.expect_response(lambda r: "/imports/grades/review" in r.url):
            review.click()
        expect(confirmation).to_be_disabled()
        page.get_by_label("Decisión fila 1", exact=True).select_option("keep")
        with page.expect_response(lambda r: "/imports/grades/commit" in r.url):
            confirmation.click()
        assert next(g for g in api("GET", "/grades") if g["id"] == first["id"])["score"] == 17
        page.get_by_label("score fila 1", exact=True).fill("5")
        expect(confirmation).to_be_disabled()
        with page.expect_response(lambda r: "/imports/grades/review" in r.url):
            review.click()
        page.get_by_label("Decisión fila 1", exact=True).select_option("update")
        with page.expect_response(lambda r: "/imports/grades/commit" in r.url) as reply:
            confirmation.click()
        assert reply.value.json()["updated"] == 1
        final = api("GET", "/grades")
        assert len(final) == 10
        assert next(g for g in final if g["id"] == first["id"])["score"] == 5
        passed("teacher_edit_keep_explicit_update_preserves_ids")

        verify_saved(catalog, student, course, period, final)


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        # Playwright exceptions can contain filled passwords: do not print them.
        location = [
            f.lineno
            for f in traceback.extract_tb(error.__traceback__)
            if f.filename.endswith("verify_institutional_import.py")
        ]
        print(
            json.dumps(
                {
                    "passed": False,
                    "error_type": type(error).__name__,
                    "script_line": location[-1] if location else None,
                }
            ),
            flush=True,
        )
        raise SystemExit(1) from None
